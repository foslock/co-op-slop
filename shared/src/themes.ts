import type { Archetype, ColliderDef, InteractDef, PartDef } from './types';

// Compact builders so the catalog below stays readable.
const box = (w: number, h: number, d: number, x: number, y: number, z: number, color: number, rot?: { rx?: number; rz?: number }): PartDef => ({
  shape: 'box', size: [w, h, d], pos: [x, y, z], color, rotX: rot?.rx, rotZ: rot?.rz,
});
const cyl = (r: number, h: number, x: number, y: number, z: number, color: number, rBottom = r, rot?: { rx?: number; rz?: number }): PartDef => ({
  shape: 'cyl', size: [r, h, rBottom], pos: [x, y, z], color, rotX: rot?.rx, rotZ: rot?.rz,
});
const sph = (rx: number, ry: number, rz: number, x: number, y: number, z: number, color: number): PartDef => ({
  shape: 'sphere', size: [rx, ry, rz], pos: [x, y, z], color,
});
const tor = (r: number, tube: number, x: number, y: number, z: number, color: number, rot?: { rx?: number; rz?: number }, arc = 1): PartDef => ({
  shape: 'torus', size: [r, tube, arc], pos: [x, y, z], color, rotX: rot?.rx, rotZ: rot?.rz,
});
const cbox = (w: number, h: number, d: number, x: number, y: number, z: number, rot?: { rx?: number; rz?: number }): ColliderDef => ({
  shape: 'box', size: [w, h, d], pos: [x, y, z], rotX: rot?.rx, rotZ: rot?.rz,
});
const ccyl = (r: number, h: number, x: number, y: number, z: number): ColliderDef => ({ shape: 'cyl', size: [r, h, 0], pos: [x, y, z] });

// Repeat a part-maker at n evenly spaced offsets — rivets, slats, keys, rungs.
const rep = (n: number, from: number, to: number, make: (t: number, i: number) => PartDef): PartDef[] =>
  Array.from({ length: n }, (_, i) => make(n === 1 ? from : from + ((to - from) * i) / (n - 1), i));

const A = (id: string, topY: number, topRadius: number, pathable: boolean, parts: PartDef[], colliders: ColliderDef[], interact?: InteractDef): Archetype => ({
  id, topY, topRadius, pathable, parts, colliders, ...(interact ? { interact } : {}),
});

// Touch-response builder. `parts` are positioned relative to `pivot` and are
// kept out of the merged level mesh so they can be animated per prop.
const touch = (
  pivot: [number, number, number],
  kind: InteractDef['kind'],
  sound: InteractDef['sound'],
  parts: PartDef[],
  opts: { radius?: number; duration?: number; hint?: string } = {},
): InteractDef => ({
  parts, pivot, kind, sound,
  radius: opts.radius ?? 2.6,
  duration: opts.duration ?? 1.1,
  ...(opts.hint ? { hint: opts.hint } : {}),
});

